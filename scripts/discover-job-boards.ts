/**
 * Finds the public job boards of the companies in src/lib/private-jobs/seed-companies.ts
 * and writes the verified ones to src/lib/private-jobs/global-catalog.ts
 * (shown in Admin → Job feeds → Catalog).
 *
 *   npx tsx scripts/discover-job-boards.ts            # resume / fill gaps
 *   npx tsx scripts/discover-job-boards.ts --fresh    # re-check everything
 *
 * Progress is kept in .cache/job-board-discovery.jsonl so an interrupted run resumes.
 */
import fs from "node:fs"
import path from "node:path"
import { discoverBoard, plausibleBoard } from "../src/lib/private-jobs/discovery"
import { SEED_COMPANIES } from "../src/lib/private-jobs/seed-companies"

const CACHE = path.join(process.cwd(), ".cache", "job-board-discovery.jsonl")
const OUT = path.join(process.cwd(), "src", "lib", "private-jobs", "global-catalog.ts")
const CONCURRENCY = 16
/** Same name, different company (checked by hand). */
const EXCLUDE = new Set(["BREEZY:census", "RECRUITEE:zara"])

interface Row {
  name: string
  sector: string
  provider?: string
  token?: string
  jobs?: number
}

function readCache(): Row[] {
  if (!fs.existsSync(CACHE)) return []
  return fs
    .readFileSync(CACHE, "utf8")
    .split("\n")
    .filter((l) => l.trim())
    .map((l) => JSON.parse(l) as Row)
}

export function writeCatalog(rows: Row[]) {
  const seen = new Set<string>()
  const entries = rows
    .filter((r) => r.provider && r.token && plausibleBoard({ provider: r.provider, token: r.token, jobs: r.jobs }))
    // Personio feeds carry no company name: for well-known brands only clearly active boards.
    .filter((r) => r.provider !== "PERSONIO" || (r.jobs ?? 0) >= 10)
    .filter((r) => !EXCLUDE.has(`${r.provider}:${r.token}`))
    .filter((r) => {
      const key = `${r.provider}:${r.token!.toLowerCase()}`
      if (seen.has(key)) return false
      seen.add(key)
      return true
    })
    .sort((a, b) => a.sector.localeCompare(b.sector) || a.name.localeCompare(b.name))
    .map((r) => {
      const id = `${r.provider!.slice(0, 2).toLowerCase()}-${r.token!.toLowerCase().replace(/[^a-z0-9]+/g, "-")}`
      return `  { id: ${JSON.stringify(id)}, company: ${JSON.stringify(r.name)}, website: null, provider: ${JSON.stringify(r.provider)}, token: ${JSON.stringify(r.token)}, sector: ${JSON.stringify(r.sector)}, jobs: ${r.jobs} },`
    })
  fs.writeFileSync(
    OUT,
    `import type { CatalogEntry } from "@/lib/private-jobs/catalog"\n\n/** Generated by scripts/discover-job-boards.ts on ${new Date().toISOString().slice(0, 10)} - do not edit by hand. */\nexport const GLOBAL_BOARDS: CatalogEntry[] = [\n${entries.join("\n")}\n]\n`
  )
  return entries.length
}

async function main() {
  fs.mkdirSync(path.dirname(CACHE), { recursive: true })
  if (process.argv.includes("--fresh") && fs.existsSync(CACHE)) fs.unlinkSync(CACHE)
  const done = new Set(readCache().map((r) => r.name))
  const queue = SEED_COMPANIES.filter((c) => !done.has(c.name))
  console.log(`${SEED_COMPANIES.length} companies, ${queue.length} to check`)
  let n = 0
  const worker = async () => {
    for (let c = queue.shift(); c; c = queue.shift()) {
      const board = await discoverBoard({ name: c.name }, { deadline: Date.now() + 45_000 }).catch(() => null)
      fs.appendFileSync(CACHE, JSON.stringify({ name: c.name, sector: c.sector, ...(board ?? {}) }) + "\n")
      if (++n % 50 === 0) console.log(`  ${n}/${queue.length + n}`)
    }
  }
  await Promise.all(Array.from({ length: CONCURRENCY }, worker))
  const count = writeCatalog(readCache())
  console.log(`Wrote ${count} verified boards to ${path.relative(process.cwd(), OUT)}`)
}

if (process.argv[1]?.includes("discover-job-boards")) void main()
